def markdown(text: str) -> str:
    """Keep authored text literal in Markdown, including HTML-like notation."""
    escaped = escape(str(text), quote=False)
    return re.sub(r'([\\`*_{}\[\]()#+!|])', r'\\\1', escaped)


def phase_id(name: str) -> str:
    return 'phase-' + re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def read_curriculum():
    data = json.loads((ROOT / 'src/data.json').read_text(encoding='utf-8'))
    foundations = json.loads((ROOT / 'src/foundations.json').read_text(encoding='utf-8'))
    validate(data)
    days = foundations['lessons']
    assert [day['day'] for day in days] == list(range(1, 7))
    assert len({day['id'] for day in days}) == len(days)
    assert all(day['title'] and day['outcome'] and day['activeMinutes'] > 0 for day in days)
    phases = OrderedDict()
    for module in data['modules']:
        assert re.fullmatch(r'[a-z][0-9]{2}', module['id']), 'Unsafe module anchor'
        phases.setdefault(module['phase'], []).append(module)
    assert len({phase_id(name) for name in phases}) == len(phases), 'Duplicate phase anchor'
    return data, days, phases


