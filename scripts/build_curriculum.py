def build_curriculum(*, check: bool = False) -> tuple[Path, Path]:
    data, days, phases = read_curriculum()
    rendered = (render_markdown(data, days, phases), render_html(data, days, phases))
    paths = tuple(ROOT / name for name in OUTPUTS)
    stale = []
    for path, content in zip(paths, rendered):
        if check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if stale:
        raise ValueError('Generated curriculum index is out of date: ' + ', '.join(stale) + '. Run python3 scripts/build_curriculum.py')
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated files without changing them')
    args = parser.parse_args()
    try:
        paths = build_curriculum(check=args.check)
    except ValueError as error:
        parser.exit(1, str(error) + '\n')
    print(('Verified' if args.check else 'Generated') + ' curriculum indexes: ' + ', '.join(str(path.relative_to(ROOT)) for path in paths))


if __name__ == '__main__':
    main()
